const Color = function(arr) {
  const [red, green, blue] = arr
  function getHexValue(intInput) {
    let result = intInput.toString(16);
    if (result.length < 2) {
      result = "0" + result;
    }
    return result;
  }
  return `#${getHexValue(red)}${getHexValue(green)}${getHexValue(blue)}`;
};

